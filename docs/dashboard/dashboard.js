/* Static client-side dashboard: no framework, no build step, no server.
   Data comes from ../data/counties.json and ../data/ny_nj_ct_counties.geojson,
   both generated by src/build_site_data.py. */

// ColorBrewer "Oranges" 5-class sequential palette (colorblind-safe with
// the luminance steps; counties additionally carry white borders).
const PALETTE = ["#feedde", "#fdbe85", "#fd8d3c", "#e6550d", "#a63603"];
const NO_DATA_COLOR = "#e8e8e8";
const DEFAULT_METRIC = "drive_time_min";
const SVG_W = 900, SVG_H = 640, PAD = 10;

const state = { data: null, geo: null, metric: null, selected: null, paths: {} };

async function init() {
  let data, geo;
  try {
    [data, geo] = await Promise.all([
      fetch("../data/counties.json").then(r => r.json()),
      fetch("../data/ny_nj_ct_counties.geojson").then(r => r.json()),
    ]);
  } catch (err) {
    // Most common cause: the file was opened directly (file://), where the
    // browser blocks fetch. Explain how to view it properly instead of
    // leaving a blank page.
    showLoadError();
    return;
  }
  state.data = data;
  state.geo = geo;
  state.metric = DEFAULT_METRIC in data.fields ? DEFAULT_METRIC : Object.keys(data.fields)[0];

  buildMetricSelect();
  buildSearch();
  drawMap();
  recolor();

  // If index scores ever appear in the data, swap the matrix placeholder
  // for the real chart.
  if (hasField("svi") && hasField("scai")) activateMatrix();
}

// Renders a friendly, on-page explanation when the data files can't be
// fetched (textContent/DOM only — no innerHTML, no alert, no console-only).
function showLoadError() {
  const box = document.getElementById("load-error");
  if (!box) return;

  const heading = document.createElement("strong");
  heading.textContent = "The dashboard data couldn't be loaded.";

  const p1 = document.createElement("p");
  p1.textContent = "This usually happens when the page is opened directly from a " +
    "file (file://), which browsers block from loading the data. The dashboard " +
    "needs to be viewed over http.";

  const p2 = document.createElement("p");
  p2.textContent = "View the live site at ";
  const link = document.createElement("a");
  link.href = "https://palism1.github.io/stroke-burden-index/dashboard/";
  link.textContent = "palism1.github.io/stroke-burden-index/dashboard/";
  p2.appendChild(link);
  p2.appendChild(document.createTextNode(", or serve it locally by running "));
  const code = document.createElement("code");
  code.textContent = "python3 -m http.server";
  p2.appendChild(code);
  p2.appendChild(document.createTextNode(" from the docs/ folder and opening the " +
    "printed http:// address."));

  box.appendChild(heading);
  box.appendChild(p1);
  box.appendChild(p2);
  box.hidden = false;
}

function hasField(f) {
  return f in state.data.fields &&
    Object.values(state.data.counties).some(c => c[f] !== null && c[f] !== undefined);
}

function fieldLabel(f) {
  const meta = state.data.fields[f];
  return meta.unit ? `${meta.label} (${meta.unit})` : meta.label;
}

// --- controls ---------------------------------------------------------

function buildMetricSelect() {
  const select = document.getElementById("metric-select");
  for (const f of Object.keys(state.data.fields)) {
    if (!hasField(f)) continue;
    const opt = document.createElement("option");
    opt.value = f;
    opt.textContent = fieldLabel(f);
    if (f === state.metric) opt.selected = true;
    select.appendChild(opt);
  }
  select.addEventListener("change", () => { state.metric = select.value; recolor(); });
}

function buildSearch() {
  const input = document.getElementById("county-search");
  const list = document.getElementById("county-list");
  const message = document.getElementById("search-message");
  const byName = {};
  for (const [fips, c] of Object.entries(state.data.counties)) {
    const name = `${c.county}, ${c.state}`;
    byName[name.toLowerCase()] = fips;
    const opt = document.createElement("option");
    opt.value = name;
    list.appendChild(opt);
  }
  input.addEventListener("change", () => {
    const raw = input.value.trim();
    const fips = byName[raw.toLowerCase()];
    if (fips) {
      if (message) message.textContent = "";
      selectCounty(fips);
    } else if (raw && message) {
      // textContent only — never innerHTML with user input.
      message.textContent = `No county found matching "${raw}"`;
    }
  });
  // Clear a stale "not found" message as soon as the user edits the input.
  input.addEventListener("input", () => { if (message) message.textContent = ""; });
}

// --- map --------------------------------------------------------------

function projector() {
  // Equirectangular with cosine latitude correction — fine at regional scale.
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  const rings = [];
  forEachRing(state.geo, (ring) => rings.push(ring));
  let latSum = 0, latN = 0;
  for (const ring of rings) for (const [, lat] of ring) { latSum += lat; latN++; }
  const cosLat = Math.cos((latSum / latN) * Math.PI / 180);
  for (const ring of rings) for (const [lon, lat] of ring) {
    const x = lon * cosLat, y = -lat;
    if (x < minX) minX = x; if (x > maxX) maxX = x;
    if (y < minY) minY = y; if (y > maxY) maxY = y;
  }
  const scale = Math.min((SVG_W - 2 * PAD) / (maxX - minX), (SVG_H - 2 * PAD) / (maxY - minY));
  return ([lon, lat]) => [
    PAD + (lon * cosLat - minX) * scale,
    PAD + (-lat - minY) * scale,
  ];
}

function forEachRing(geo, fn, feature) {
  const targets = feature ? [feature] : geo.features;
  for (const feat of targets) {
    const g = feat.geometry;
    const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
    for (const poly of polys) for (const ring of poly) fn(ring);
  }
}

function drawMap() {
  const svg = document.getElementById("map");
  svg.setAttribute("viewBox", `0 0 ${SVG_W} ${SVG_H}`);
  const project = projector();

  for (const feat of state.geo.features) {
    const fips = feat.properties.fips;
    let d = "";
    forEachRing(state.geo, (ring) => {
      d += ring.map((pt, i) => (i ? "L" : "M") + project(pt).map(v => v.toFixed(1)).join(",")).join("") + "Z";
    }, feat);

    const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
    path.setAttribute("d", d);
    path.setAttribute("class", "county");
    path.setAttribute("tabindex", "0");
    path.setAttribute("role", "button");
    path.dataset.fips = fips;
    path.addEventListener("click", () => selectCounty(fips));
    path.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); selectCounty(fips); }
    });
    const title = document.createElementNS("http://www.w3.org/2000/svg", "title");
    path.appendChild(title);
    svg.appendChild(path);
    state.paths[fips] = path;
  }
}

// --- coloring ---------------------------------------------------------

function quantileBreaks(values, n) {
  const sorted = [...values].sort((a, b) => a - b);
  const breaks = [];
  for (let i = 1; i < n; i++) {
    breaks.push(sorted[Math.floor((i / n) * sorted.length)]);
  }
  // With few distinct values the quantile cuts can coincide, which would
  // give legend entries identical/overlapping ranges. Drop duplicates so
  // each break (and thus each class) spans a distinct, non-degenerate range.
  // Fewer breaks simply means fewer classes.
  return [...new Set(breaks)];
}

// Pick a light-to-dark subset of PALETTE with exactly `n` colors so that,
// when there are fewer than PALETTE.length classes, the shades stay far
// enough apart to remain distinguishable (rather than using the first n).
function paletteSubset(n) {
  if (n >= PALETTE.length) return PALETTE;
  if (n <= 1) return [PALETTE[PALETTE.length - 1]];
  return Array.from({ length: n }, (_, i) =>
    PALETTE[Math.round((i / (n - 1)) * (PALETTE.length - 1))]);
}

function recolor() {
  const metric = state.metric;
  const values = Object.values(state.data.counties)
    .map(c => c[metric]).filter(v => v !== null && v !== undefined);
  const breaks = quantileBreaks(values, PALETTE.length);
  const palette = paletteSubset(breaks.length + 1);

  const classOf = (v) => {
    let k = 0;
    while (k < breaks.length && v >= breaks[k]) k++;
    return k;
  };

  for (const [fips, c] of Object.entries(state.data.counties)) {
    const path = state.paths[fips];
    const v = c[metric];
    path.setAttribute("fill", v === null || v === undefined ? NO_DATA_COLOR : palette[classOf(v)]);
    path.querySelector("title").textContent =
      `${c.county}, ${c.state} — ${fieldLabel(metric)}: ${formatValue(v)}`;
    path.setAttribute("aria-label", `${c.county} County, ${c.state}`);
  }
  drawLegend(breaks, values, palette);
}

function drawLegend(breaks, values, palette) {
  const legend = document.getElementById("legend");
  legend.innerHTML = "";
  const lo = Math.min(...values), hi = Math.max(...values);
  const edges = [lo, ...breaks, hi];
  palette.forEach((color, i) => {
    const item = document.createElement("span");
    item.className = "legend-item";
    const swatch = document.createElement("span");
    swatch.className = "legend-swatch";
    swatch.style.background = color;
    item.appendChild(swatch);
    item.appendChild(document.createTextNode(`${fmtNum(edges[i])} – ${fmtNum(edges[i + 1])}`));
    legend.appendChild(item);
  });
  const title = document.createElement("strong");
  title.textContent = fieldLabel(state.metric) + ": ";
  legend.prepend(title);
}

// --- details panel ----------------------------------------------------

function selectCounty(fips) {
  if (state.selected) state.paths[state.selected].classList.remove("selected");
  state.selected = fips;
  const path = state.paths[fips];
  path.classList.add("selected");
  const svg = document.getElementById("map");
  svg.appendChild(path); // raise above neighbors so the outline isn't clipped

  const c = state.data.counties[fips];
  document.getElementById("details-title").textContent = `${c.county} County, ${c.state}`;
  document.getElementById("details-hint").textContent = "";

  const body = document.getElementById("details-body");
  body.innerHTML = "";
  for (const [group, groupTitle] of Object.entries(state.data.groups)) {
    const fields = Object.keys(state.data.fields)
      .filter(f => state.data.fields[f].group === group && hasField(f));
    if (!fields.length) continue;
    const div = document.createElement("div");
    div.className = "detail-group";
    const h = document.createElement("h3");
    h.textContent = groupTitle;
    div.appendChild(h);
    for (const f of fields) {
      const row = document.createElement("div");
      row.className = "detail-row";
      const label = document.createElement("span");
      label.textContent = state.data.fields[f].label;
      const value = document.createElement("span");
      const v = c[f];
      value.className = "value" + (v === null || v === undefined ? " na" : "");
      value.textContent = formatValue(v, state.data.fields[f].unit);
      row.appendChild(label);
      row.appendChild(value);
      div.appendChild(row);
    }
    body.appendChild(div);
  }
}

// --- matrix (activates when index scores exist) -----------------------

function activateMatrix() {
  document.getElementById("matrix-placeholder").hidden = true;
  const chart = document.getElementById("matrix-chart");
  chart.hidden = false;
  chart.textContent = "Index scores detected — matrix chart implementation goes here.";
}

// --- formatting -------------------------------------------------------

function fmtNum(v) {
  if (v >= 1000) return Math.round(v).toLocaleString();
  return (Math.round(v * 10) / 10).toLocaleString();
}

function formatValue(v, unit) {
  if (v === null || v === undefined) return "Not available";
  const n = typeof v === "number" ? fmtNum(v) : v;
  if (!unit) return n;
  if (unit === "%") return `${n}%`;
  return `${n} ${unit}`;
}

init();
