/* Static client-side dashboard: no framework, no build step, no server.
   Data comes from ../data/counties.json and ../data/ny_nj_ct_counties.geojson,
   both generated by src/build_site_data.py. */

// ColorBrewer "Oranges" 5-class sequential palette (colorblind-safe with
// the luminance steps; counties additionally carry white borders).
const PALETTE = ["#feedde", "#fdbe85", "#fd8d3c", "#e6550d", "#a63603"];
const NO_DATA_COLOR = "#e8e8e8";
const DEFAULT_METRIC = "drive_time_min";
const SVG_W = 900, SVG_H = 640, PAD = 10;

// Zoom/pan tuning. Zoom is expressed as a factor over the full extent, so
// MIN_ZOOM = 1 means the whole map fits exactly and MAX_ZOOM = 12 is the
// tightest we ever let the view get (protects tiny counties from becoming
// microscopic and keeps outlines meaningful). DRAG_THRESHOLD_PX separates a
// click-that-selects from a real pan so a small pointer wobble still selects.
const MIN_ZOOM = 1, MAX_ZOOM = 12;
const WHEEL_STEP = 1.0015;      // per unit of deltaY; e^(deltaY*ln(step))-ish feel
const BUTTON_ZOOM = 1.5;        // +/- buttons multiply/divide the current zoom
const DRAG_THRESHOLD_PX = 4;    // screen px of motion before a drag suppresses select
const ZOOM_ANIM_MS = 300;       // zoom-to-selection ease duration

// view holds the live viewBox {x,y,w,h}; bboxes maps fips -> projected county
// bounding box {x,y,w,h} in SVG units (filled during drawMap, used by
// zoom-to-selection). anim tracks an in-flight zoom ease so a new one cancels
// it. _testSyncAnim makes the ease resolve in a single frame (smoke harness).
const state = {
  data: null, geo: null, metric: null, selected: null, paths: {},
  view: { x: 0, y: 0, w: SVG_W, h: SVG_H },
  bboxes: {},
  anim: null,
  _testSyncAnim: false,
  // Risk-vs-Access matrix: dots[fips] -> that county's scatter <circle>, kept
  // parallel to paths[] so selectCounty() can toggle .selected on both the map
  // path and the matrix dot from a single place (map click, search, or dot click).
  dots: {},
};

// --- matrix (Risk vs Access scatter) layout ---------------------------------
// Its own coordinate space, independent of the map's. PLOT is the drawable
// data area inside the axis margins; MARGIN leaves room for axis labels/ticks.
const MTX_W = 640, MTX_H = 460;
const MTX_MARGIN = { top: 16, right: 16, bottom: 52, left: 56 };
const MTX_PLOT = {
  x: MTX_MARGIN.left,
  y: MTX_MARGIN.top,
  w: MTX_W - MTX_MARGIN.left - MTX_MARGIN.right,
  h: MTX_H - MTX_MARGIN.top - MTX_MARGIN.bottom,
};
// Scores are 0-100 by construction, so the axes are fixed 0..100 (stable across
// data updates, and the 75th/25th quadrant lines read against a known scale).
const MTX_MIN = 0, MTX_MAX = 100;
const SVGNS = "http://www.w3.org/2000/svg";

async function init() {
  let data, geo;
  try {
    [data, geo] = await Promise.all([
      fetch("../data/counties.json").then(r => r.json()),
      fetch("../data/ny_nj_ct_counties.geojson").then(r => r.json()),
    ]);
  } catch (err) {
    // Most common cause: the file was opened directly (file://), where the
    // browser blocks fetch. Explain how to view it properly instead of
    // leaving a blank page.
    showLoadError();
    return;
  }
  state.data = data;
  state.geo = geo;
  state.metric = DEFAULT_METRIC in data.fields ? DEFAULT_METRIC : Object.keys(data.fields)[0];

  buildMetricSelect();
  buildSearch();
  drawMap();
  recolor();

  // If index scores ever appear in the data, swap the matrix placeholder
  // for the real chart.
  if (hasField("sri") && hasField("scai")) activateMatrix();
}

// Renders a friendly, on-page explanation when the data files can't be
// fetched (textContent/DOM only — no innerHTML, no alert, no console-only).
function showLoadError() {
  const box = document.getElementById("load-error");
  if (!box) return;

  const heading = document.createElement("strong");
  heading.textContent = "The dashboard data couldn't be loaded.";

  const p1 = document.createElement("p");
  p1.textContent = "This usually happens when the page is opened directly from a " +
    "file (file://), which browsers block from loading the data. The dashboard " +
    "needs to be viewed over http.";

  const p2 = document.createElement("p");
  p2.textContent = "View the live site at ";
  const link = document.createElement("a");
  link.href = "https://palism1.github.io/stroke-burden-index/dashboard/";
  link.textContent = "palism1.github.io/stroke-burden-index/dashboard/";
  p2.appendChild(link);
  p2.appendChild(document.createTextNode(", or serve it locally by running "));
  const code = document.createElement("code");
  code.textContent = "python3 -m http.server";
  p2.appendChild(code);
  p2.appendChild(document.createTextNode(" from the docs/ folder and opening the " +
    "printed http:// address."));

  box.appendChild(heading);
  box.appendChild(p1);
  box.appendChild(p2);
  box.hidden = false;
}

// A value counts as "missing" if it's null/undefined or a non-finite number
// (NaN/Infinity from a bad upstream calc). Everything that decides between a
// real value and the "no data" treatment routes through here so the choropleth,
// tooltips, and details panel stay consistent.
function isMissing(v) {
  return v === null || v === undefined || (typeof v === "number" && !Number.isFinite(v));
}

function hasField(f) {
  return f in state.data.fields &&
    Object.values(state.data.counties).some(c => !isMissing(c[f]));
}

function fieldLabel(f) {
  const meta = state.data.fields[f];
  return meta.unit ? `${meta.label} (${meta.unit})` : meta.label;
}

// --- controls ---------------------------------------------------------

function buildMetricSelect() {
  const select = document.getElementById("metric-select");
  for (const f of Object.keys(state.data.fields)) {
    if (!hasField(f)) continue;
    const opt = document.createElement("option");
    opt.value = f;
    opt.textContent = fieldLabel(f);
    if (f === state.metric) opt.selected = true;
    select.appendChild(opt);
  }
  select.addEventListener("change", () => { state.metric = select.value; recolor(); });
}

function buildSearch() {
  const input = document.getElementById("county-search");
  const list = document.getElementById("county-list");
  const message = document.getElementById("search-message");
  const byName = {};
  for (const [fips, c] of Object.entries(state.data.counties)) {
    const name = `${c.county}, ${c.state}`;
    byName[name.toLowerCase()] = fips;
    const opt = document.createElement("option");
    opt.value = name;
    list.appendChild(opt);
  }
  input.addEventListener("change", () => {
    const raw = input.value.trim();
    const fips = byName[raw.toLowerCase()];
    if (fips) {
      if (message) message.textContent = "";
      selectCounty(fips);
    } else if (raw && message) {
      // textContent only — never innerHTML with user input.
      message.textContent = `No county found matching "${raw}"`;
    }
  });
  // Clear a stale "not found" message as soon as the user edits the input.
  input.addEventListener("input", () => { if (message) message.textContent = ""; });
}

// --- map --------------------------------------------------------------

function projector() {
  // Equirectangular with cosine latitude correction — fine at regional scale.
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  const rings = [];
  forEachRing(state.geo, (ring) => rings.push(ring));
  let latSum = 0, latN = 0;
  for (const ring of rings) for (const [, lat] of ring) { latSum += lat; latN++; }
  const cosLat = Math.cos((latSum / latN) * Math.PI / 180);
  for (const ring of rings) for (const [lon, lat] of ring) {
    const x = lon * cosLat, y = -lat;
    if (x < minX) minX = x; if (x > maxX) maxX = x;
    if (y < minY) minY = y; if (y > maxY) maxY = y;
  }
  const scale = Math.min((SVG_W - 2 * PAD) / (maxX - minX), (SVG_H - 2 * PAD) / (maxY - minY));
  return ([lon, lat]) => [
    PAD + (lon * cosLat - minX) * scale,
    PAD + (-lat - minY) * scale,
  ];
}

function forEachRing(geo, fn, feature) {
  const targets = feature ? [feature] : geo.features;
  for (const feat of targets) {
    const g = feat.geometry;
    const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
    for (const poly of polys) for (const ring of poly) fn(ring);
  }
}

function drawMap() {
  const svg = document.getElementById("map");
  state.view = { x: 0, y: 0, w: SVG_W, h: SVG_H };
  applyView();
  const project = projector();

  for (const feat of state.geo.features) {
    const fips = feat.properties.fips;
    let d = "";
    // Track the projected extent of this feature so we can later frame it.
    let bx0 = Infinity, by0 = Infinity, bx1 = -Infinity, by1 = -Infinity;
    forEachRing(state.geo, (ring) => {
      d += ring.map((pt, i) => {
        const [px, py] = project(pt);
        if (px < bx0) bx0 = px; if (px > bx1) bx1 = px;
        if (py < by0) by0 = py; if (py > by1) by1 = py;
        return (i ? "L" : "M") + px.toFixed(1) + "," + py.toFixed(1);
      }).join("") + "Z";
    }, feat);
    state.bboxes[fips] = { x: bx0, y: by0, w: bx1 - bx0, h: by1 - by0 };

    const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
    path.setAttribute("d", d);
    path.setAttribute("class", "county");
    path.setAttribute("tabindex", "0");
    path.setAttribute("role", "button");
    path.dataset.fips = fips;
    path.addEventListener("click", () => {
      // A pan that crossed the drag threshold suppresses the trailing click so
      // dragging never selects a county (see attachZoomPan).
      if (svg._suppressClick) { svg._suppressClick = false; return; }
      selectCounty(fips);
    });
    path.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); selectCounty(fips); }
    });
    const title = document.createElementNS("http://www.w3.org/2000/svg", "title");
    path.appendChild(title);
    svg.appendChild(path);
    state.paths[fips] = path;
  }

  attachZoomPan(svg);
  buildZoomControls();
}

// --- zoom & pan -------------------------------------------------------
//
// Everything is driven by the SVG viewBox only: no re-projection and no
// transforms on the paths (vector-effect:non-scaling-stroke in the CSS keeps
// outlines hairline at any zoom). state.view is the single source of truth;
// applyView() is the only place that writes the attribute.

function applyView() {
  const svg = document.getElementById("map");
  if (!svg) return;
  const v = state.view;
  svg.setAttribute("viewBox", `${v.x} ${v.y} ${v.w} ${v.h}`);
}

// Clamp a candidate view to the allowed zoom range and keep it inside the
// full SVG extent so panning can never wander off the map into blank space.
function clampView(v) {
  // Enforce zoom limits via width; height follows the fixed aspect ratio.
  const minW = SVG_W / MAX_ZOOM, maxW = SVG_W / MIN_ZOOM;
  let w = Math.min(maxW, Math.max(minW, v.w));
  let h = w * (SVG_H / SVG_W);
  // Keep the box within [0,0]..[SVG_W,SVG_H]; if it's as wide/tall as the
  // extent it pins to the edge (max(0, ...) handles the equal case).
  let x = Math.min(Math.max(0, v.x), Math.max(0, SVG_W - w));
  let y = Math.min(Math.max(0, v.y), Math.max(0, SVG_H - h));
  return { x, y, w, h };
}

// Zoom by `factor` (>1 zooms in) keeping the SVG point (cx,cy) fixed on screen.
function zoomAt(cx, cy, factor) {
  cancelAnim();
  const v = state.view;
  let w = v.w / factor;
  // Pre-clamp width so the fixed-point math uses the final scale.
  w = Math.min(SVG_W / MIN_ZOOM, Math.max(SVG_W / MAX_ZOOM, w));
  const h = w * (SVG_H / SVG_W);
  // Keep (cx,cy) at the same fractional position within the box.
  const fx = (cx - v.x) / v.w, fy = (cy - v.y) / v.h;
  state.view = clampView({ x: cx - fx * w, y: cy - fy * h, w, h });
  applyView();
}

// Zoom about the current view center (used by the +/- buttons).
function zoomByCenter(factor) {
  const v = state.view;
  zoomAt(v.x + v.w / 2, v.y + v.h / 2, factor);
}

function resetView() {
  cancelAnim();
  state.view = { x: 0, y: 0, w: SVG_W, h: SVG_H };
  applyView();
}

// Map a screen (client) point to SVG-user coordinates using the svg's
// on-screen box. In the smoke shim there's no layout, so getBoundingClientRect
// returns a zero-origin box the size of the extent — cursor-centered zoom then
// degenerates gracefully to top-left origin (still a valid zoom for the test).
function clientToSvg(svg, clientX, clientY) {
  const r = svg.getBoundingClientRect
    ? svg.getBoundingClientRect()
    : { left: 0, top: 0, width: SVG_W, height: SVG_H };
  const w = r.width || SVG_W, h = r.height || SVG_H;
  const v = state.view;
  return {
    x: v.x + ((clientX - r.left) / w) * v.w,
    y: v.y + ((clientY - r.top) / h) * v.h,
  };
}

function attachZoomPan(svg) {
  // Wheel zoom, centered on the cursor. Bare wheel (no ctrl needed); we call
  // preventDefault so the page doesn't scroll while zooming the map.
  svg.addEventListener("wheel", (e) => {
    if (e.preventDefault) e.preventDefault();
    const p = clientToSvg(svg, e.clientX || 0, e.clientY || 0);
    // deltaY<0 (wheel up) zooms in. Exponential feel, framerate-independent.
    const factor = Math.pow(WHEEL_STEP, -(e.deltaY || 0));
    zoomAt(p.x, p.y, factor);
  });

  // Pointer drag to pan. We track motion in screen px; once it passes
  // DRAG_THRESHOLD_PX we mark it a real drag and suppress the trailing click.
  let dragging = false, moved = false, lastX = 0, lastY = 0, startX = 0, startY = 0;

  svg.addEventListener("pointerdown", (e) => {
    dragging = true; moved = false;
    // A new gesture ends any earlier suppression; without this, a drag that
    // ended over the background would swallow the next legitimate click.
    svg._suppressClick = false;
    lastX = startX = e.clientX || 0;
    lastY = startY = e.clientY || 0;
  });

  svg.addEventListener("pointermove", (e) => {
    if (!dragging) return;
    // If the button was released where we couldn't hear it (capture not yet
    // taken), don't let a hover re-entry continue a phantom drag.
    if (e.buttons != null && e.buttons === 0) { dragging = false; return; }
    const cx = e.clientX || 0, cy = e.clientY || 0;
    if (!moved &&
        Math.abs(cx - startX) + Math.abs(cy - startY) >= DRAG_THRESHOLD_PX) {
      moved = true;
      cancelAnim();
      svg._suppressClick = true;
      // Capture only once a real drag starts. Capturing on pointerdown makes
      // browsers retarget the trailing click off the county path, which would
      // break plain click-to-select.
      if (svg.setPointerCapture && e.pointerId != null) {
        try { svg.setPointerCapture(e.pointerId); } catch (_) { /* shim/no-op */ }
      }
    }
    if (!moved) { lastX = cx; lastY = cy; return; }
    // Convert the screen delta to SVG units and shift the box the opposite way
    // (drag right -> content follows the cursor -> view moves left).
    const r = svg.getBoundingClientRect
      ? svg.getBoundingClientRect()
      : { width: SVG_W, height: SVG_H };
    const sw = r.width || SVG_W, sh = r.height || SVG_H;
    const dx = (cx - lastX) * (state.view.w / sw);
    const dy = (cy - lastY) * (state.view.h / sh);
    state.view = clampView({ x: state.view.x - dx, y: state.view.y - dy,
      w: state.view.w, h: state.view.h });
    applyView();
    lastX = cx; lastY = cy;
  });

  const endDrag = (e) => {
    if (!dragging) return;
    dragging = false;
    // _suppressClick was already set when the threshold was crossed (and is
    // cleared on the next pointerdown), so the trailing click after a real
    // drag is swallowed while a sub-threshold press still selects normally.
    if (svg.releasePointerCapture && e && e.pointerId != null) {
      try { svg.releasePointerCapture(e.pointerId); } catch (_) { /* no-op */ }
    }
  };
  svg.addEventListener("pointerup", endDrag);
  svg.addEventListener("pointercancel", endDrag);
  // Pinch-to-zoom is intentionally skipped: robust two-pointer tracking with
  // capture/cancel edge cases isn't worth the complexity here, and mobile QA
  // is a separate backlog item. Single-finger drag still pans via the pointer
  // handlers above.
}

// Build the +/- /reset overlay. Real <button>s (focusable, aria-labelled),
// appended to the map section so they float over the SVG (see dashboard.css).
function buildZoomControls() {
  const section = document.getElementById("map-section");
  if (!section || section.querySelector(".zoom-controls")) return;
  const wrap = document.createElement("div");
  wrap.className = "zoom-controls";

  const mk = (label, aria, onClick) => {
    const b = document.createElement("button");
    b.type = "button";
    b.className = "zoom-btn";
    b.textContent = label;
    b.setAttribute("aria-label", aria);
    b.addEventListener("click", onClick);
    wrap.appendChild(b);
    return b;
  };
  mk("+", "Zoom in", () => zoomByCenter(BUTTON_ZOOM));
  mk("−", "Zoom out", () => zoomByCenter(1 / BUTTON_ZOOM));
  mk("↺", "Reset zoom", () => resetView());

  section.appendChild(wrap);
}

// --- zoom-to-selection ------------------------------------------------

function cancelAnim() {
  if (state.anim != null) {
    if (typeof cancelAnimationFrame === "function") cancelAnimationFrame(state.anim);
    state.anim = null;
  }
}

// Compute the target view that frames a county's padded bbox. The county
// should fill very roughly half the view, so we scale the bbox up and enforce
// a sensible minimum size so tiny counties (Manhattan, Kings) don't zoom to a
// microscopic extent and large ones don't over-zoom past MAX_ZOOM.
function targetViewFor(fips) {
  const bb = state.bboxes[fips];
  if (!bb) return null;
  // Aim for the county spanning ~1/2 of each axis -> frame ~2x the bbox.
  const FILL = 0.5;
  let w = bb.w / FILL;
  let h = bb.h / FILL;
  // Respect the map aspect ratio: grow the smaller axis to match SVG_W:SVG_H.
  const aspect = SVG_W / SVG_H;
  if (w / h < aspect) w = h * aspect; else h = w / aspect;
  // Never tighter than MAX_ZOOM (keeps tiny counties readable), never looser
  // than the full extent.
  const minW = SVG_W / MAX_ZOOM;
  if (w < minW) { w = minW; h = w / aspect; }
  if (w > SVG_W) { w = SVG_W; h = SVG_H; }
  const cx = bb.x + bb.w / 2, cy = bb.y + bb.h / 2;
  return clampView({ x: cx - w / 2, y: cy - h / 2, w, h });
}

// Animate state.view -> target with a short ease-out. Returns a promise that
// resolves when the ease completes (the smoke harness awaits it). When
// _testSyncAnim is set, or rAF is unavailable, it jumps straight to the target.
function animateView(target) {
  cancelAnim();
  const from = { ...state.view };
  const noRaf = typeof requestAnimationFrame !== "function";
  if (state._testSyncAnim || noRaf) {
    state.view = target;
    applyView();
    return Promise.resolve();
  }
  return new Promise((resolve) => {
    const t0 = (typeof performance !== "undefined" && performance.now)
      ? performance.now() : Date.now();
    const ease = (t) => 1 - Math.pow(1 - t, 3); // cubic ease-out
    const step = (now) => {
      const t = Math.min(1, (now - t0) / ZOOM_ANIM_MS);
      const k = ease(t);
      state.view = {
        x: from.x + (target.x - from.x) * k,
        y: from.y + (target.y - from.y) * k,
        w: from.w + (target.w - from.w) * k,
        h: from.h + (target.h - from.h) * k,
      };
      applyView();
      if (t < 1) { state.anim = requestAnimationFrame(step); }
      else { state.anim = null; resolve(); }
    };
    state.anim = requestAnimationFrame(step);
  });
}

// --- coloring ---------------------------------------------------------

function quantileBreaks(values, n) {
  const sorted = [...values].sort((a, b) => a - b);
  const breaks = [];
  for (let i = 1; i < n; i++) {
    breaks.push(sorted[Math.floor((i / n) * sorted.length)]);
  }
  // With few distinct values the quantile cuts can coincide, which would
  // give legend entries identical/overlapping ranges. Drop duplicates so
  // each break (and thus each class) spans a distinct, non-degenerate range.
  // Fewer breaks simply means fewer classes.
  return [...new Set(breaks)];
}

// Pick a light-to-dark subset of PALETTE with exactly `n` colors so that,
// when there are fewer than PALETTE.length classes, the shades stay far
// enough apart to remain distinguishable (rather than using the first n).
function paletteSubset(n) {
  if (n >= PALETTE.length) return PALETTE;
  if (n <= 1) return [PALETTE[PALETTE.length - 1]];
  return Array.from({ length: n }, (_, i) =>
    PALETTE[Math.round((i / (n - 1)) * (PALETTE.length - 1))]);
}

function recolor() {
  const metric = state.metric;
  const values = Object.values(state.data.counties)
    .map(c => c[metric]).filter(v => !isMissing(v));
  const breaks = quantileBreaks(values, PALETTE.length);
  const palette = paletteSubset(breaks.length + 1);

  const classOf = (v) => {
    let k = 0;
    while (k < breaks.length && v >= breaks[k]) k++;
    return k;
  };

  for (const [fips, c] of Object.entries(state.data.counties)) {
    const path = state.paths[fips];
    const v = c[metric];
    path.setAttribute("fill", isMissing(v) ? NO_DATA_COLOR : palette[classOf(v)]);
    path.querySelector("title").textContent =
      `${c.county}, ${c.state} — ${fieldLabel(metric)}: ${formatValue(v)}`;
    path.setAttribute("aria-label", `${c.county} County, ${c.state}`);
  }
  drawLegend(breaks, values, palette);
}

function drawLegend(breaks, values, palette) {
  const legend = document.getElementById("legend");
  legend.innerHTML = "";
  const lo = Math.min(...values), hi = Math.max(...values);
  const edges = [lo, ...breaks, hi];
  palette.forEach((color, i) => {
    const item = document.createElement("span");
    item.className = "legend-item";
    const swatch = document.createElement("span");
    swatch.className = "legend-swatch";
    swatch.style.background = color;
    item.appendChild(swatch);
    item.appendChild(document.createTextNode(`${fmtNum(edges[i])} – ${fmtNum(edges[i + 1])}`));
    legend.appendChild(item);
  });
  const title = document.createElement("strong");
  title.textContent = fieldLabel(state.metric) + ": ";
  legend.prepend(title);
}

// --- details panel ----------------------------------------------------

function selectCounty(fips) {
  // Clear the previous selection on BOTH surfaces (map + matrix), then mark the
  // new one on both, so selection stays in sync no matter what triggered it
  // (map click, search box, or a matrix dot click). dots may be empty when the
  // matrix hasn't activated — the guard handles that.
  if (state.selected) {
    state.paths[state.selected].classList.remove("selected");
    if (state.dots[state.selected]) state.dots[state.selected].classList.remove("selected");
  }
  state.selected = fips;
  const path = state.paths[fips];
  path.classList.add("selected");
  const svg = document.getElementById("map");
  svg.appendChild(path); // raise above neighbors so the outline isn't clipped

  const dot = state.dots[fips];
  if (dot) {
    dot.classList.add("selected");
    // Raise the selected dot above its neighbors so the emphasis ring shows.
    if (dot.parentNode) dot.parentNode.appendChild(dot);
  }

  // Frame the selected county (map click or search) with a short ease.
  const target = targetViewFor(fips);
  if (target) animateView(target);

  const c = state.data.counties[fips];
  document.getElementById("details-title").textContent = `${c.county} County, ${c.state}`;
  document.getElementById("details-hint").textContent = "";

  const body = document.getElementById("details-body");
  body.innerHTML = "";
  for (const [group, groupTitle] of Object.entries(state.data.groups)) {
    const fields = Object.keys(state.data.fields)
      .filter(f => state.data.fields[f].group === group && hasField(f));
    if (!fields.length) continue;
    const div = document.createElement("div");
    div.className = "detail-group";
    const h = document.createElement("h3");
    h.textContent = groupTitle;
    div.appendChild(h);
    for (const f of fields) {
      const row = document.createElement("div");
      row.className = "detail-row";
      const label = document.createElement("span");
      label.textContent = state.data.fields[f].label;
      const value = document.createElement("span");
      const v = c[f];
      value.className = "value" + (isMissing(v) ? " na" : "");
      value.textContent = formatValue(v, state.data.fields[f].unit);
      row.appendChild(label);
      row.appendChild(value);
      div.appendChild(row);
    }
    body.appendChild(div);
  }
}

// --- matrix (Risk vs Access scatter; activates when index scores exist) ----
//
// X = SRI (stroke risk; left low -> right high). Y = SCAI (access to care)
// oriented so HIGHER access sits HIGHER on screen — SVG y grows downward, so
// the y scale inverts. One dot per county; dots link to selectCounty() exactly
// like the map paths (same click / keyboard / .selected treatment), so the two
// views stay in lockstep through the shared selection state.

// Linear percentile of an already-known score list (textbook / numpy-default
// interpolation between closest ranks). Used for the 75th-SRI and 25th-SCAI
// quadrant lines, computed from the plotted scores so the caption is exact.
function percentile(values, p) {
  const sorted = [...values].sort((a, b) => a - b);
  if (sorted.length === 0) return NaN;
  const idx = (p / 100) * (sorted.length - 1);
  const lo = Math.floor(idx), hi = Math.min(lo + 1, sorted.length - 1);
  return sorted[lo] + (sorted[hi] - sorted[lo]) * (idx - lo);
}

// Map a score (0..100) to an SVG x / y within the plot area. y inverts so a
// higher SCAI lands nearer the top.
function mtxX(score) {
  return MTX_PLOT.x + ((score - MTX_MIN) / (MTX_MAX - MTX_MIN)) * MTX_PLOT.w;
}
function mtxY(score) {
  return MTX_PLOT.y + (1 - (score - MTX_MIN) / (MTX_MAX - MTX_MIN)) * MTX_PLOT.h;
}

function mtxLine(x1, y1, x2, y2, cls) {
  const ln = document.createElementNS(SVGNS, "line");
  ln.setAttribute("x1", x1.toFixed(1));
  ln.setAttribute("y1", y1.toFixed(1));
  ln.setAttribute("x2", x2.toFixed(1));
  ln.setAttribute("y2", y2.toFixed(1));
  if (cls) ln.setAttribute("class", cls);
  return ln;
}

function mtxText(x, y, text, cls) {
  const t = document.createElementNS(SVGNS, "text");
  t.setAttribute("x", x.toFixed(1));
  t.setAttribute("y", y.toFixed(1));
  if (cls) t.setAttribute("class", cls);
  t.textContent = text;
  return t;
}

function activateMatrix() {
  document.getElementById("matrix-placeholder").hidden = true;
  const chart = document.getElementById("matrix-chart");
  chart.hidden = false;
  chart.innerHTML = "";

  const counties = Object.entries(state.data.counties)
    .filter(([, c]) => !isMissing(c.sri) && !isMissing(c.scai));
  const sriVals = counties.map(([, c]) => c.sri);
  const scaiVals = counties.map(([, c]) => c.scai);
  const sri75 = percentile(sriVals, 75);   // vertical line: high-risk boundary
  const scai25 = percentile(scaiVals, 25); // horizontal line: low-access boundary

  const svg = document.createElementNS(SVGNS, "svg");
  svg.setAttribute("id", "matrix-svg");
  svg.setAttribute("viewBox", `0 0 ${MTX_W} ${MTX_H}`);
  svg.setAttribute("role", "img");
  svg.setAttribute("aria-label",
    "Scatter plot of counties by stroke risk (SRI) versus access to stroke care (SCAI)");

  // Critical-intervention quadrant tint: high SRI (right of the vertical line)
  // AND low SCAI (below the horizontal line, since low access sits low on
  // screen). A subtle fill, not a shout — it just draws the eye to the deserts.
  const critX = mtxX(sri75), critY = mtxY(scai25);
  const critRect = document.createElementNS(SVGNS, "rect");
  critRect.setAttribute("class", "mtx-critical-zone");
  critRect.setAttribute("x", critX.toFixed(1));
  critRect.setAttribute("y", critY.toFixed(1));
  critRect.setAttribute("width", (MTX_PLOT.x + MTX_PLOT.w - critX).toFixed(1));
  critRect.setAttribute("height", (MTX_PLOT.y + MTX_PLOT.h - critY).toFixed(1));
  svg.appendChild(critRect);

  // Plot frame.
  const frame = document.createElementNS(SVGNS, "rect");
  frame.setAttribute("class", "mtx-frame");
  frame.setAttribute("x", MTX_PLOT.x);
  frame.setAttribute("y", MTX_PLOT.y);
  frame.setAttribute("width", MTX_PLOT.w);
  frame.setAttribute("height", MTX_PLOT.h);
  svg.appendChild(frame);

  // Quadrant divider lines.
  svg.appendChild(mtxLine(critX, MTX_PLOT.y, critX, MTX_PLOT.y + MTX_PLOT.h, "mtx-quadrant-line"));
  svg.appendChild(mtxLine(MTX_PLOT.x, critY, MTX_PLOT.x + MTX_PLOT.w, critY, "mtx-quadrant-line"));

  // Quadrant labels (plan §3.7 language). Placed in each quadrant's outer
  // corner so they don't collide with the dot cloud in the middle.
  const loX = (MTX_PLOT.x + critX) / 2, hiX = (critX + MTX_PLOT.x + MTX_PLOT.w) / 2;
  const topY = MTX_PLOT.y + 14, botY = MTX_PLOT.y + MTX_PLOT.h - 8;
  // Top row = higher access (good); bottom row = lower access (poor).
  svg.appendChild(mtxText(loX, topY, "System working well", "mtx-quad-label"));
  svg.appendChild(mtxText(hiX, topY, "Prevention focus", "mtx-quad-label"));
  svg.appendChild(mtxText(loX, botY, "Monitor for change", "mtx-quad-label"));
  const critLabel = mtxText(hiX, botY, "Critical intervention", "mtx-quad-label mtx-quad-label-critical");
  svg.appendChild(critLabel);

  // Axis lines.
  svg.appendChild(mtxLine(MTX_PLOT.x, MTX_PLOT.y + MTX_PLOT.h,
    MTX_PLOT.x + MTX_PLOT.w, MTX_PLOT.y + MTX_PLOT.h, "mtx-axis"));
  svg.appendChild(mtxLine(MTX_PLOT.x, MTX_PLOT.y, MTX_PLOT.x, MTX_PLOT.y + MTX_PLOT.h, "mtx-axis"));

  // Axis titles with direction arrows (higher x = riskier, higher y = better access).
  svg.appendChild(mtxText(MTX_PLOT.x + MTX_PLOT.w / 2, MTX_H - 12,
    "Stroke risk (SRI) →", "mtx-axis-title"));
  const yTitle = mtxText(0, 0, "Access to care (SCAI) →", "mtx-axis-title");
  // Rotate the y-title up the left edge (arrow then points upward = more access).
  const yx = 16, yy = MTX_PLOT.y + MTX_PLOT.h / 2;
  yTitle.setAttribute("x", yx);
  yTitle.setAttribute("y", yy);
  yTitle.setAttribute("transform", `rotate(-90 ${yx} ${yy})`);
  svg.appendChild(yTitle);

  // One dot per county. Selection/keyboard/tooltip mirror the map paths exactly.
  state.dots = {};
  for (const [fips, c] of counties) {
    const dot = document.createElementNS(SVGNS, "circle");
    dot.setAttribute("class", "mtx-dot");
    dot.setAttribute("cx", mtxX(c.sri).toFixed(1));
    dot.setAttribute("cy", mtxY(c.scai).toFixed(1));
    dot.setAttribute("r", "5");
    dot.setAttribute("tabindex", "0");
    dot.setAttribute("role", "button");
    dot.dataset.fips = fips;
    const label = `${c.county} County, ${c.state}. ` +
      `Stroke risk ${fmtNum(c.sri)}, access to care ${fmtNum(c.scai)}.`;
    dot.setAttribute("aria-label", label);
    dot.addEventListener("click", () => selectCounty(fips));
    dot.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); selectCounty(fips); }
    });
    const title = document.createElementNS(SVGNS, "title");
    title.textContent =
      `${c.county}, ${c.state} — SRI ${fmtNum(c.sri)}, SCAI ${fmtNum(c.scai)}`;
    dot.appendChild(title);
    if (fips === state.selected) dot.classList.add("selected");
    svg.appendChild(dot);
    state.dots[fips] = dot;
  }

  chart.appendChild(svg);

  // Caption: state the exact quadrant thresholds (the plotted percentiles).
  const caption = document.createElement("p");
  caption.className = "mtx-caption";
  caption.textContent =
    `Each dot is one county. Quadrant lines mark the 75th percentile of stroke risk ` +
    `(SRI ${fmtNum(sri75)}) and the 25th percentile of access (SCAI ${fmtNum(scai25)}) ` +
    `across the plotted counties. The shaded corner — high risk and low access — is the ` +
    `stroke care deserts / critical-intervention quadrant.`;
  chart.appendChild(caption);
}

// --- formatting -------------------------------------------------------

// Numbers >= 1000 read as whole counts with thousands separators (e.g.
// population, density). Smaller numbers keep a fixed single decimal so a
// column of values lines up (3.0 / 12.0 / 3.6) instead of raggedly mixing
// "3" with "3.6" — the details rows use tabular-nums for exactly this.
function fmtNum(v) {
  if (v >= 1000) return Math.round(v).toLocaleString();
  return v.toLocaleString(undefined, { minimumFractionDigits: 1, maximumFractionDigits: 1 });
}

function formatValue(v, unit) {
  if (isMissing(v)) return "Not available";
  const n = typeof v === "number" ? fmtNum(v) : v;
  if (!unit) return n;
  if (unit === "%") return `${n}%`;
  return `${n} ${unit}`;
}

